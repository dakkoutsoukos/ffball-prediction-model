# Freezing the Milestone 3 rule challengers ---------------------------------------------
# The constants below are the pre-registered rules of experiment log E6
# (docs/milestone3_plan.md). They were derived from development seasons
# 2020-2023 only (residual = actual - calibrated ESPN, weekly rolling) and
# halved to guard against winner's-curse inflation. write_m3_registry() writes
# them to models/registry/m3.yml once; the file is never edited afterwards.

M3_ROLE_RULE <- list(metric = "xfp_trend", hi = 1.42, lo = -1.65, adj_hi = -0.30, adj_lo = 0.25)
M3_ROLE_RULE_Q20 <- list(metric = "xfp_trend", hi = 0.80, lo = -1.11, adj_hi = -0.27, adj_lo = 0.16)
M3_RETURN_RULE <- list(adj_one = -0.2, adj_two_plus = -0.4)

write_m3_registry <- function(path = "models/registry/m3.yml", parent_commit = git_state()$commit,
                              calibration = "components_recency") {
  if (file.exists(path)) cli::cli_abort("{.file {path}} exists: frozen registries are never overwritten.")
  base <- list(type = "adjusted", calibration = calibration, features = ESPN_COMPONENTS)
  reg <- list(
    lineage = "M3",
    frozen_parent_commit = parent_commit,
    frozen_at_utc = format(Sys.time(), "%Y-%m-%dT%H:%M:%SZ", tz = "UTC"),
    selection_rationale = paste(
      "Pre-registered narrow hypotheses (experiment log E6). Base = calibrated ESPN with the same",
      "family and weekly refit procedure as frozen m2_espn_cal. Thresholds = development (2020-2023)",
      "deciles/quintiles of xfp_trend among ESPN-projected WRs; magnitudes = half the development",
      "mean residual of the group (shrunk for winner's curse). No parameter is learned at run time."),
    data = list(history_start_season = 2017, min_train_season = 2018, population = "pop_espn",
                scoring = "espn_ppr", feature_windows = c(3, 8),
                feature_engine = "add_m2_features + add_absence_features"),
    training_procedure = paste(
      "Expanding window: the calibrated-ESPN base is refit before each target week on every eligible",
      "row from final games strictly before it; the fixed adjustment is added at prediction time."),
    models = list(
      m3_role_adjust_v1 = c(base, list(role_rule = M3_ROLE_RULE,
                                       hypothesis = "A: ESPN over-reacts to sharp recent role changes (primary)")),
      m3_role_adjust_q20_v1 = c(base, list(role_rule = M3_ROLE_RULE_Q20,
                                           hypothesis = "A sensitivity: quintile thresholds")),
      m3_return_adjust_v1 = c(base, list(return_rule = M3_RETURN_RULE,
                                         hypothesis = "B: ESPN over-projects WRs returning from missed games")),
      m3_combined_v1 = c(base, list(role_rule = M3_ROLE_RULE, return_rule = M3_RETURN_RULE,
                                    hypothesis = "A + B additive (pre-registered combination)"))
    ),
    fingerprint = "models/fingerprints/m3_holdout_2024_2025.csv",
    versioning = "Any change to a rule creates a new id (e.g. *_v2) with a new prospective start; v1 records stay as they are.",
    environment = list(r_version = as.character(getRversion()), lockfile = "renv.lock at the freeze commit")
  )
  dir.create(dirname(path), recursive = TRUE, showWarnings = FALSE)
  writeLines(c("# FROZEN - Milestone 3 rule challengers. Generated by write_m3_registry(); do not edit.",
               "# A changed rule must be registered under a NEW id with its own prospective record.",
               yaml::as.yaml(reg)), path)
  path
}
