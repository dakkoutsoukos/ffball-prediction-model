# Freezing the Milestone 4 availability challengers -------------------------------------
# Selected by the pre-registered rule (docs/milestone4_plan.md section 10;
# experiment log E13 and E14). Their parameters are the fixed values in
# research/m4_candidate_params.yml (derived from 2020-2023 only, committed in
# 39b8059 before the 2019 and 2024 checks). write_m4_registry() writes them to
# models/registry/m4.yml once; the file is never edited afterwards.

#' Registry builder: calibrated ESPN (refit weekly, the m2_espn_cal family)
#' times a fixed availability multiplier (m4_rule_multiplier()).
registry_spec_availability_adjusted <- function(m, id) {
  base <- spec_cal(m$calibration)
  rule <- m$availability_rule
  list(
    name = id, features = base$features,
    fit = function(train) base$fit(train),
    predict = function(fit, newdata) base$predict(fit, newdata) * m4_rule_multiplier(newdata, rule)
  )
}

write_m4_registry <- function(params, path = "models/registry/m4.yml", parent_commit = git_state()$commit,
                              calibration = "components_recency") {
  if (file.exists(path)) cli::cli_abort("{.file {path}} exists: frozen registries are never overwritten.")
  rules <- m4_rules(params)
  base <- list(type = "availability_adjusted", calibration = calibration, features = ESPN_COMPONENTS)
  reg <- list(
    lineage = "M4",
    frozen_parent_commit = parent_commit,
    frozen_at_utc = format(Sys.time(), "%Y-%m-%dT%H:%M:%SZ", tz = "UTC"),
    selection_rationale = paste(
      "Pre-registered M4 candidates (docs/milestone4_plan.md; E12, E13). K1 and K2 met every freeze",
      "criterion (development 2020-2023 pooled CI below 0 vs m2_espn_cal, and 2019 better than both",
      "m2_espn_cal and M3b with RMSE no worse). K2 is better than K1 in both development and 2019, so it",
      "is the PRIMARY M4 challenger by the simplicity rule's exception; K1 is frozen as a secondary.",
      "Parameters were fixed from 2020-2023 before the 2019/2024 checks. No parameter is learned at run time."),
    data = list(history_start_season = 2017, min_train_season = 2018, population = "pop_espn",
                scoring = "espn_ppr", feature_windows = c(3, 8),
                feature_engine = "add_m2_features + add_absence_features + m4_add_features",
                injury_timing = paste(
                  "historical: final weekly report, date_modified < own kickoff (2017-2020 Pacific fix);",
                  "2025 excluded. prospective: our retrieval time < own kickoff, and the team's final report",
                  "must be out (at least one game designation for the team-week); earlier weeks' rows",
                  "feed lagged features only (live_injury_detail)."),
                parameters_file = "research/m4_candidate_params.yml",
                parameters_fixed_in_commit = "39b8059 (pushed before the 2019/2024 checks)"),
    training_procedure = "Calibrated-ESPN base refit weekly on final games (as m2_espn_cal); fixed multiplier applied.",
    models = list(
      m4_two_stage_v1 = c(base, list(availability_rule = rules$K2,
                                     hypothesis = "K2: P(active) x points ratio if active, by injury group (PRIMARY)")),
      m4_practice_rule_v1 = c(base, list(availability_rule = rules$K1,
                                         hypothesis = "K1: practice-refined designation multipliers (secondary)"))
    ),
    primary = "m4_two_stage_v1",
    fingerprint = "models/fingerprints/m4_checks_2019_2024.csv",
    versioning = "Any change creates a new id (*_v2) with a new prospective start.",
    environment = list(r_version = as.character(getRversion()), lockfile = "renv.lock at the freeze commit")
  )
  writeLines(c("# FROZEN - Milestone 4 availability challengers. Generated by write_m4_registry(); do not edit.",
               yaml::as.yaml(reg)), path)
  path
}
