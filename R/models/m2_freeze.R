# Freezing the Milestone 2 lineage -----------------------------------------------------
# Writes models/registry/m2.yml from the pre-registered selection outputs, so
# the frozen definitions are generated rather than hand-copied. Run once; the
# file is then committed and never edited (a new challenger = a new lineage).

write_m2_registry <- function(selection, tuning, cal_choice, path = "models/registry/m2.yml",
                              parent_commit = git_state()$commit) {
  if (file.exists(path)) cli::cli_abort("{.file {path}} exists: frozen registries are never overwritten.")
  cal_type <- sub("^cal_", "", cal_choice$model)
  enet <- best_params(tuning, "aug_resid_enet")
  pooled <- selection$table
  row <- function(m) {
    r <- pooled[pooled$model == m, ]
    list(dev_pooled_mae = round(r$mae, 4), dev_pooled_rmse = round(r$rmse, 4))
  }
  aug_type <- switch(selection$aug,
    aug_resid_enet = list(type = "residual", calibration = cal_type, residual_model = "m2_linear",
                          penalty = enet$penalty, mixture = 0.5, features = FEATURES_M2),
    cli::cli_abort("Freezing {selection$aug} is not implemented; add its registry mapping first.")
  )
  nf_type <- switch(selection$nf,
    nf_ols = list(type = "m2_linear", penalty = NULL, features = FEATURES_M2),
    cli::cli_abort("Freezing {selection$nf} is not implemented; add its registry mapping first.")
  )
  reg <- list(
    lineage = "M2",
    frozen_parent_commit = parent_commit,
    frozen_at_utc = format(Sys.time(), "%Y-%m-%dT%H:%M:%SZ", tz = "UTC"),
    selection_rationale = paste(
      "Pre-registered rules (research/experiment_log.md, E3) on development folds 2020-2023",
      "(weekly expanding-window refits from 2018). Calibrated ESPN = best pooled MAE in the",
      "ESPN-only calibration family. ESPN-free challenger = lowest pooled MAE among nf_*.",
      "Augmentation challenger = lowest pooled MAE among aug_* with pooled RMSE <= calibrated ESPN."
    ),
    data = list(history_start_season = 2017, min_train_season = 2018, population = "pop_espn",
                scoring = "espn_ppr", feature_windows = c(3, 8), feature_engine = "add_m2_features",
                excluded_inputs = "betting lines, injury reports, inactives, routes/participation, depth charts"),
    training_procedure = paste(
      "Expanding window. Before each target week, refit on every eligible row (population above,",
      "season >= min_train_season, final games only) whose game_index is strictly less than the",
      "target week's; predict the target week."),
    models = list(
      m2_espn_cal = c(list(type = "cal", calibration = cal_type, features = ESPN_COMPONENTS), row(cal_choice$model)),
      m2_no_espn = c(nf_type, list(selected_from = selection$nf), row(selection$nf)),
      m2_espn_aug = c(aug_type, list(selected_from = selection$aug), row(selection$aug))
    ),
    fingerprint = "models/fingerprints/m2_holdout_2024_2025.csv",
    environment = list(r_version = as.character(getRversion()),
                       xgboost = as.character(utils::packageVersion("xgboost")),
                       glmnet = as.character(utils::packageVersion("glmnet")),
                       lockfile = "renv.lock at the freeze commit")
  )
  dir.create(dirname(path), recursive = TRUE, showWarnings = FALSE)
  writeLines(c("# FROZEN - Milestone 2 lineage. Generated by write_m2_registry(); do not edit.",
               "# A changed model must be registered as a NEW lineage with its own record.",
               yaml::as.yaml(reg)), path)
  path
}
