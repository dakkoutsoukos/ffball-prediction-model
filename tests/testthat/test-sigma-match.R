# S0 level-shock matching (master plan S0, VL3). Synthetic data only.

sm_table <- function() read_pod_table(file.path(project_root, "models", "probabilistic", "pod_baseline_v0.yml"))

test_that("inverse-CDF draws interpolate on the tau grid and hold the tails", {
  tau <- c(0.1, 0.5, 0.9)
  q <- matrix(c(0, 10, 20), nrow = 3, ncol = 3, byrow = TRUE)
  expect_equal(sim_qdraw(q, c(0.05, 0.3, 0.95), tau), c(0, 5, 20))
  set.seed(1)
  u <- stats::runif(20000)
  x <- sim_qdraw(matrix(stats::qnorm(POD_TAU), 20000, length(POD_TAU), byrow = TRUE), u)
  expect_equal(stats::median(x), 0, tolerance = 0.03)
})

test_that("matching recovers a known level-shock scale from data generated by the model", {
  tab <- sm_table()
  set.seed(42)
  G <- 3000
  weeks <- 8
  rows <- tibble::tibble(group = rep(paste0("g", seq_len(G)), each = weeks), position = "WR",
                         lvl = rep(stats::runif(G, 6, 16), each = weeks), A = 0.9)
  rows$E <- rows$A * rows$lvl
  # "observed" totals generated with sigma_L = 0.3 through the same components
  q <- pd_quantiles(rows$position, rows$lvl, tab)
  true_s <- 0.3
  L <- rep(exp(-true_s^2 / 2 + true_s * stats::rnorm(G)), each = weeks)
  rows$pts <- ifelse(stats::runif(nrow(rows)) < rows$A, L * sim_qdraw(q, stats::runif(nrow(rows))), 0)
  rows$w <- 6L
  prep <- sim_match_prepare(rows, tab, draws = 100, seed = 7)
  s <- sim_match_sigma(prep)
  wr <- s[s$position == "WR", ]
  expect_equal(wr$sigma_L, true_s, tolerance = 0.05)
  expect_lt(wr$sd_sim_at_0, wr$sd_observed)              # without the shock the spread is too narrow
  expect_equal(wr$sd_sim_matched, wr$sd_observed, tolerance = 1e-3)
  # the level shock preserves the mean: E[L] = 1
  set.seed(3)
  expect_equal(mean(exp(-0.37^2 / 2 + 0.37 * stats::rnorm(2e5))), 1, tolerance = 0.005)
})

test_that("the frozen S0 parameters load with one sigma_L per position", {
  p <- read_s0_params(file.path(project_root, "models", "simulation", "s0_params_v0.yml"))
  expect_setequal(names(p$sigma_L), POD_POSITIONS)
  expect_true(all(p$sigma_L > 0 & p$sigma_L < 1))
  expect_equal(p$pre_registration, "VL3")
})

test_that("frozen YAML files are written once with LF line endings", {
  f <- file.path(withr::local_tempdir(), "x.yml")
  write_frozen_yaml(list(a = 1), f, "header")
  raw <- readBin(f, "raw", file.size(f))
  expect_false(any(raw == as.raw(13)))                     # no carriage returns
  expect_error(write_frozen_yaml(list(a = 2), f, "header"), "frozen")
})
